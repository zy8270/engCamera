/** 应用语言模式：跟随系统 / 中文 / English */
enum class AppLanguageMode { SYSTEM, ZH, EN }

/**
 * 轻量国际化（v191，用户拍板 2026-10-16 全量中英）：中文串即键，英文查词典、
 * 未命中回退中文。用法：UI 内 `t("拍照")`；非组合语境（VM 等）`I18n.t("拍照失败")`。
 * 模式由仓库持久化并在启动时桥接到 I18n.mode；SYSTEM 按系统locale 取中文/英文。
 * 水印内容数据（默认字段值/位置文本等）不进词典——它们是用户数据不是界面文字。
 */
object I18n {
    // Compose 快照状态（非 StateFlow.value——后者组合内读取不订阅，切语言不重组，
    // 用户实测只有部分文字刷新，v194 修复）：组合内任意 I18n.t() 读取都自动订阅
    var mode by mutableStateOf(AppLanguageMode.SYSTEM)

    fun isZh(): Boolean = when (mode) {
        AppLanguageMode.ZH -> true
        AppLanguageMode.EN -> false
        AppLanguageMode.SYSTEM -> Locale.getDefault().language.startsWith("zh")
    }

    fun t(zh: String): String = if (isZh()) zh else EN_DICT[zh] ?: zh
}

/** 组合内翻译：mode 为快照状态，读取即订阅（保留便捷入口，与 I18n.t 等价） */
@Composable
fun t(zh: String): String = I18n.t(zh)

