/** 由主题模式与系统深浅色解析实际是否夜间主题 */
fun resolveDarkTheme(mode: ThemeMode, systemDark: Boolean): Boolean = when (mode) {
    ThemeMode.SYSTEM -> systemDark
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
}

/** 当前应用是否夜间主题（MainActivity 在根组合提供；用于系统栏图标对比度） */
val LocalAppDarkTheme = staticCompositionLocalOf { true }

/**
 * 应用主题：跟随系统或手动日/夜（设置抽屉"外观"切换）。
 * 注意：取景器上的浮层控件（快门、角标等）不随主题，见 Color.kt 的 Chrome* 系列。
 */
@Composable
fun EngCameraTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit,
) {
    val dark = resolveDarkTheme(themeMode, isSystemInDarkTheme())
    MaterialTheme(
        colorScheme = if (dark) DarkColorScheme else LightColorScheme,
        content = content,
    )
}
